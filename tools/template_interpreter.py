def scan_sets(project_root: str) -> tuple[list[str], str, str]:
    """Return (import_lines, map_entries, warning) for a project's scenes/sets/*.js."""
    sets_dir = os.path.join(project_root, 'scenes', 'sets')
    if not os.path.isdir(sets_dir):
        return [], '', ''
    names = []
    for fn in sorted(os.listdir(sets_dir)):
        if fn.endswith('.js'):
            names.append(fn[:-3])
    if not names:
        return [], '', f'no set modules found in {sets_dir}'
    imports = '\n'.join(f"import {{ {n} }} from '../sets/{n}.js';" for n in names)
    entries = ', '.join(f'{n}' for n in names)
    return imports, entries, ''


def emit_shot(shot: dict, tmpl: str, sets_imports: str, sets_map: str) -> str:
    a = ARCHMOD.get(tmpl)
    size = a['size']
    # archetype camera/freeze defaults, merged only where the author didn't set them
    arch = dict(a.get('cam') or {})
    if a.get('freeze') is not None and 'freeze' not in (shot.get('params') or {}):
        arch['freeze'] = a['freeze']
    if size == 'card':
        body = BODY_CARD
    else:
        body = BODY_STAGE
    out = (body
           .replace('@@TMPL@@', tmpl)
           .replace('@@ID@@', shot['id'])
           .replace('@@SIZE@@', size or 'wide')
           .replace('@@ARCH@@', json.dumps(arch))
           .replace('@@SETS_IMPORTS@@', sets_imports)
           .replace('@@SETS_MAP@@', sets_map))
    return out


def run(shots: dict, project_root: str, out_dir: str, dry_run: bool, do_check: bool) -> dict:
    sets_imports, sets_map, sets_warn = scan_sets(project_root)
    shot_list = shots.get('shots') or []
    emitted, skipped, warns = [], [], []
    if sets_warn:
        warns.append(f'[sets] {sets_warn} (shots will use a fallback empty set; add scenes/sets/*.js to render)')
    for shot in shot_list:
        tmpl = shot.get('template')
        if not tmpl:
            continue  # hand-written or director-generated — not our job
        vid = shot['id']
        a = ARCHMOD.get(tmpl)
        if a is None:
            skipped.append(vid)
            warns.append(f'[{vid}] unknown template "{tmpl}" — skipped')
            continue
        if a.get('generator') is False:
            skipped.append(vid)
            warns.append(f'[{vid}] template "{tmpl}" is a hand-written hero shot — skipped (author writes it)')
            continue
        warns.extend(f'[{vid}] ' + w for w in ARCHMOD.validate_shot(shot))
        code = emit_shot(shot, tmpl, sets_imports, sets_map)
        fname = f'{vid}.tpl.js'
        fpath = os.path.join(out_dir, fname)
        if dry_run:
            emitted.append((fname, code))
        else:
            os.makedirs(out_dir, exist_ok=True)
            with open(fpath, 'w', encoding='utf-8') as fh:
                fh.write(code)
            emitted.append((fname, fpath))
    if do_check and emitted:
        node = _find_node()
        if node:
            for fname, _ in emitted:
                fpath = os.path.join(out_dir, fname) if dry_run else _
                if dry_run:
                    # write to a temp file for syntax check
                    tmp = os.path.join(out_dir, '_chk_' + fname)
                    with open(tmp, 'w', encoding='utf-8') as fh:
                        fh.write(_ if isinstance(_, str) else open(fpath, encoding='utf-8').read())
                    _check_file(node, tmp)
                    os.remove(tmp)
                else:
                    _check_file(node, fpath)
        else:
            warns.append('[check] node not found on PATH — skipping syntax check')
    return {'emitted': [f for f, _ in emitted], 'skipped': skipped, 'warnings': warns}


def _find_node() -> str:
    for cand in ('node', 'node.exe'):
        try:
            subprocess.run([cand, '--version'], capture_output=True, check=True)
            return cand
        except Exception:
            continue
    return ''


def _check_file(node: str, path: str):
    try:
        r = subprocess.run([node, '--check', path], capture_output=True, text=True)
        if r.returncode != 0:
            print(f'  SYNTAX FAIL {os.path.basename(path)}:\n{r.stderr.strip()}')
        else:
            print(f'  syntax ok   {os.path.basename(path)}')
    except Exception as e:
        print(f'  check error {os.path.basename(path)}: {e}')


def main(argv=None):
    ap = argparse.ArgumentParser(description='template + params interpreter')
    ap.add_argument('--project', help='project dir under projects/ (or a path to a project root)')
    ap.add_argument('--shots', help='path to a shots.json (alternative to --project)')
    ap.add_argument('--out', help='output dir for emitted shot JS (default <project>/scenes/shots)')
    ap.add_argument('--dry-run', action='store_true', help='print/save to out but do not write into the project')
    ap.add_argument('--check', action='store_true', help='run node --check on emitted files')
    args = ap.parse_args(argv)

    if not args.project and not args.shots:
        ap.error('provide --project <slug> or --shots <path>')
    if args.shots:
        shots_path = args.shots
        project_root = args.out or os.path.dirname(os.path.abspath(shots_path))
        if not args.out:
            project_root = os.path.dirname(os.path.dirname(os.path.abspath(shots_path)))  # best guess
    else:
        proj = args.project
        # accept either a slug or a full path
        candidate = proj if os.path.isdir(proj) else os.path.join(HERE, '..', 'projects', proj)
        if not os.path.isdir(candidate):
            ap.error(f'project not found: {proj}')
        project_root = os.path.abspath(candidate)
        shots_path = os.path.join(project_root, 'story', 'shots.json')
    if not os.path.isfile(shots_path):
        ap.error(f'shots.json not found: {shots_path}')
    shots = json.load(open(shots_path, encoding='utf-8'))
    out_dir = args.out or os.path.join(project_root, 'scenes', 'shots')
    res = run(shots, project_root, out_dir, args.dry_run, args.check)
    print(f"emitted {len(res['emitted'])} shot file(s): {', '.join(res['emitted']) or '-'}")
    if res['skipped']:
        print(f"skipped {len(res['skipped'])}: {', '.join(res['skipped'])}")
    for w in res['warnings']:
        print(f"  warn: {w}")


if __name__ == '__main__':
    main()
