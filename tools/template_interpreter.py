#!/usr/bin/env python3
"""
tools/template_interpreter.py — the `params` half of the template + params interpreter.

Reads a project's story/shots.json. For every shot that carries a `template` field, it
resolves the archetype (tools/archetypes.py), merges archetype camera/freeze defaults into
the params ONLY where the author did not set them, and emits a registered shot JS file into
<project>/scenes/shots/. The emitted draw body is the SAME proven, parameterised body that
tools/director.py already generates (projects/cine_release/scenes/shots/01_s001-wide.js),
so output is structurally identical to a known-good shot — just driven by `template`+`params`
instead of hand-authored Size branches.

This is ADDITIVE: it writes new scenes/shots/*.tpl.js files and never edits engine/, audio/,
render.mjs, or existing shots. It does NOT render anything.

Guards (owner rule, 2026-11-10): enhances the directing flow, no monetisation impact (our
content stays ours), no quality change (reuses the proven body), no efficiency cost unless
used. The two non-generator archetypes (blueprint-diagram, lowpoly-3d) are skipped with a
warning so the author hand-writes them — honouring the plan's "3-5 hero shots stay hand-written".

Usage:
  python tools/template_interpreter.py --project projects/<slug> [--dry-run] [--check]
  python tools/template_interpreter.py --shots path/to/shots.json --out /tmp/out [--dry-run] [--check]

--check runs `node --check` on every emitted file (syntax only; does not import the project).
"""
