def emit_cast(story, out):
    members = []
    for name, c in story["cast"].items():
        fields = ", ".join("%s: %s" % (k, json.dumps(v)) for k, v in c.items())
        members.append("export const %s = { %s };" % (name, fields))
    txt = CAST_JS.replace("__MEMBERS__", "\n".join(members)).replace(
        "__KEYS__", ", ".join(story["cast"].keys()))
    path = os.path.join(out, "scenes", "cast.js")
    open(path, "w", encoding="utf-8").write(txt)
    return path


