def set_dressing_override(out):
    """Read the dressing toggles from set_spec.json, or None."""
    path = os.path.join(out, "set_spec.json")
    if not os.path.exists(path):
        return None
    try:
        with open(path, encoding="utf-8") as fh:
            spec = json.load(fh)
    except (OSError, ValueError):
        return None
    d = spec.get("dressing")
    return d if isinstance(d, dict) and d else None


def set_palette_override(out):
    """Return the per-project set palette from set_spec.json, or None.

    `fresh/sets.py` has always written set_spec.json and nothing ever read it,
    so every film's set colours came from the five style moods instead of the
    concept. This is that missing reader: the derived palette is injected into
    the EMITTED set JS, so no engine file changes and a project without a spec
    (e.g. cine_release) emits the old template byte-for-byte.
    """
    path = os.path.join(out, "set_spec.json")
    if not os.path.exists(path):
        return None
    try:
        with open(path, encoding="utf-8") as fh:
            spec = json.load(fh)
    except (OSError, ValueError):
        return None
    pal = spec.get("palette")
    if not isinstance(pal, dict):
        return None
    keep = {}
    for k in ("wall", "floor", "practical", "dark", "accent"):
        v = pal.get(k)
        if isinstance(v, str) and v.startswith("#") and len(v) in (4, 7):
            keep[k] = v
    return keep or None


def render_set_js(template, palette, dressing=None):
    """Substitute the palette and dressing into a set template. Pure.

    Injection happens here, at emit time, rather than inside four hand-written
    JS strings: the import, the resolved toggles and the single draw call are
    added only if the template has the anchors, so a bare test string passes
    through unharmed.
    """
    js = template
    if "dressing.js" not in js:
        js = js.replace("import * as FX from '/engine/fx2d.js';",
                        "import * as FX from '/engine/fx2d.js';\n"
                        "import { dressing, DEFAULTS } from './dressing.js';", 1)
    js = js.replace("  const PROJECT_PALETTE = __PROJECT_PALETTE__;",
                    "  const PROJECT_PALETTE = __PROJECT_PALETTE__;\n"
                    "  const D = Object.assign({}, DEFAULTS, __PROJECT_DRESSING__ || {});", 1)
    js = js.replace("  return { GY",
                    "  dressing(g, D, M, GY, CX);\n  return { GY", 1)
    return (js.replace("__PROJECT_PALETTE__", json.dumps(palette) if palette else "null")
              .replace("__PROJECT_DRESSING__", json.dumps(dressing) if dressing else "null"))


