#!/usr/bin/env python3
"""
director.py — the DIRECTOR half: story/script -> renderable project.

The renderer (render.mjs) is deterministic and IDE/AI-agnostic, but it needs
scene code (scenes/shots/*.js). Historically a coding LLM hand-wrote those.
This tool is the missing no-AI bridge: it compiles a structured STORY SPEC into
a full project (config.json + scenes/cast.js + story/shots.json +
scenes/shots/NN_*.js). Each generated shot is a template driven by shot.params
(player.js:74 injects params into `info`) and uses drawFigure() + cast outfits,
so CHARACTERS actually render.

This is a deterministic template compiler: no AI, no network, no randomness.
Any tool/model can emit the JSON spec; this turns it into video-ready code.

USAGE
  python tools/director.py --demo
  python tools/director.py --story examples/director-demo/story.json --out projects/director_demo

STORY SPEC (JSON)
  {
    "title": "...", "aspect": "9:16", "resolution": "1080p", "fps": 24,
    "style": "dusk",
    "cast": { "MAX": {...}, "JAKE": {...}, "DOC": {...} },   # optional
    "shots": [
      { "id":"s001", "start":0, "end":3, "line":"...",
        "who":"MAX", "pose":"stand", "expr":"neutral",
        "x":0.5, "y":0.9, "scale":1.1, "facing":1, "bg":"dusk" }
    ]
  }
  pose: any key in rig2d POSES (stand/talk/point/cheer/sit/think/...)
  expr: any key in rig2d EXPR (neutral/happy/determined/surprised/...)
  x,y: 0..1 fraction of stage;  scale: relative multiplier (1.0 = default framing)
  who: a key in cast
"""
import argparse
import json
import os
import re
import sys

DEFAULT_CAST = {
    "MAX": {"top": "hoodie", "color": "#d64a33", "head": "none"},
    "JAKE": {"top": "tshirt", "color": "#3a6ea5", "head": "cap", "headColor": "#f2c21a"},
    "DOC": {"top": "labcoat", "face": "glasses", "head": "none"},
}

# Template: __ID__ replaced per shot. Braces are literal JS braces (no .format).
SHOT_JS = r"""// AUTO-GENERATED by tools/director.py — do not hand-edit.
import { E, V, registerShot, mood, seg, text, linGrad, circle } from '/engine/core.js';
import { drawFigure, breathe, pose } from '/engine/rig2d.js';
import { CAST } from '../cast.js';

registerShot('__ID__', { draw(g, t, info) {
  const p = info || {};                          // shot.params injected by player.js
  const dur = p.dur || 3;
  const push = 0.06 * Math.min(1, t / dur);      // gentle dolly-in so static beats still move
  const two = !!p.who2;
  const gy = E.H * (p.y ?? 0.92);

  // backdrop
  const M = mood(p.bg || 'dusk');
  const sky = (M && Array.isArray(M.sky) && M.sky.length) ? M.sky : ['#1a1b2e', '#3a2a3e'];
  g.fillStyle = linGrad(g, 0, 0, 0, E.H, sky);
  g.fillRect(0, 0, E.W, E.H);

  // simple set: horizon + ground band + soft depth blobs
  const horizon = E.H * 0.68;
  g.fillStyle = 'rgba(0,0,0,.12)'; g.fillRect(0, horizon, E.W, E.H - horizon);
  seg(g, [[0, horizon], [E.W, horizon]], 2, 'rgba(255,255,255,.10)');
  for (let i = 0; i < 4; i++) {
    const bx = E.W * (0.12 + i * 0.26), br = E.W * (0.09 + (i % 2) * 0.03);
    circle(g, bx, horizon - br * 0.6, br, 'rgba(255,255,255,.045)');
  }

  // ground contact line (under the feet)
  seg(g, [[0, gy + 4], [E.W, gy + 4]], 3, 'rgba(0,0,0,.35)');

  // character(s) — one, or two facing each other
  const baseS = (two ? V(1.3, 2.9) : V(2.0, 4.4)) * (1 + push);
  const drawOne = (who, xf, facing, pz, ex) => {
    const outfit = CAST[who] || CAST.MAX || Object.values(CAST)[0];
    drawFigure(g, {
      x: E.W * xf, y: gy + 6 * push, s: (p.scale ?? 1) * baseS, facing,
      outfit, pose: breathe(pose(pz || 'stand'), t), expr: ex || 'neutral',
      rim: { color: (M && M.rim) || '#ffc68a', dir: [0, -1], w: 3 }, shadow: true,
    });
  };
  drawOne(p.who || 'MAX', p.x ?? (two ? 0.32 : 0.5), p.facing ?? 1, p.pose, p.expr);
  if (two) drawOne(p.who2, p.x2 ?? 0.68, p.facing2 ?? -1, p.pose2, p.expr2);

  // caption: engine word-captions when timings exist, else static in-shot fallback
  if (p.line && (!E.words || !E.words.length)) text(g, p.line, E.W / 2, E.H * V(0.93, 0.95),
    { size: V(46, 54), weight: 700, color: '#fff', stroke: 4, strokeColor: 'rgba(0,0,0,.6)' });
} });
"""

CAST_JS = "// AUTO-GENERATED by tools/director.py\nexport const CAST = __CAST__;\n"


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", (s or "shot").lower()).strip("-")[:28] or "shot"


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


def build(spec, out):
    shots = spec.get("shots") or []
    if not shots:
        sys.exit("ERROR: story has no 'shots'.")
    duration = max(float(s.get("end", 0)) for s in shots)
    cast = spec.get("cast") or DEFAULT_CAST

    cfg = {
        "title": spec.get("title", "Untitled"),
        "aspect": spec.get("aspect", "9:16"),
        "resolution": spec.get("resolution", "1080p"),
        "fps": spec.get("fps", 24),
        "style": spec.get("style", "dusk"),
        "captions": False,
        "fadeIn": spec.get("fadeIn", 0.4),
        "fadeOut": spec.get("fadeOut", 0.6),
        "music": {"enabled": bool(spec.get("music", False))},
        "sfx": {"enabled": bool(spec.get("sfx", False))},
        "loudness": spec.get("loudness", -14),
    }
    write(os.path.join(out, "config.json"), json.dumps(cfg, indent=2))

    write(os.path.join(out, "scenes", "cast.js"),
          CAST_JS.replace("__CAST__", json.dumps(cast, indent=2)))

    sjson = []
    for i, s in enumerate(shots):
        sid = s.get("id") or f"s{i+1:03d}"
        params = {k: s[k] for k in ("who", "pose", "expr", "x", "y", "scale",
                                    "facing", "bg",
                                    "who2", "pose2", "expr2", "x2", "facing2") if k in s}
        sjson.append({
            "id": sid,
            "start": float(s.get("start", 0)),
            "end": float(s.get("end", 0)),
            "line": s.get("line", ""),
            "in": {"type": "cut"},
            "params": params,
        })
    write(os.path.join(out, "story", "shots.json"),
          json.dumps({"title": cfg["title"], "duration": duration,
                      "shots": sjson, "music": []}, indent=2))

    for i, s in enumerate(shots):
        sid = s.get("id") or f"s{i+1:03d}"
        fn = f"{i+1:02d}_{slug(sid + '-' + s.get('who', ''))}.js"
        write(os.path.join(out, "scenes", "shots", fn),
              SHOT_JS.replace("__ID__", sid))

    write(os.path.join(out, "README.md"),
          f"# {cfg['title']}\n\nAUTO-GENERATED by `tools/director.py` — do not hand-edit.\n\n"
          f"- shots: {len(shots)}  duration: {duration:.2f}s  aspect: {cfg['aspect']}\n"
          f"- render: `node render.mjs --project {out}`\n"
          f"- verify: `python tools/render_gate.py --project {out}`\n"
          f"- review frames: `python tools/review_frames.py --project {out} --aspect {cfg['aspect']}`\n")

    print(f"Director: wrote project -> {out}")
    print(f"  shots={len(shots)}  duration={duration:.2f}s  aspect={cfg['aspect']}  style={cfg['style']}")
    print(f"  next: node render.mjs --project {out}")
    return 0


def demo(out):
    spec = {
        "title": "Director Demo — 9:16",
        "aspect": "9:16", "resolution": "1080p", "fps": 24, "style": "dusk",
        "cast": DEFAULT_CAST,
        "shots": [
            {"id": "s001", "start": 0.0, "end": 4.0,
             "line": "A fly buzzes past your face.",
             "who": "MAX", "pose": "stand", "expr": "neutral",
             "x": 0.5, "y": 0.92, "scale": 1.1, "facing": 1, "bg": "dusk"},
            {"id": "s002", "start": 4.0, "end": 8.0,
             "line": "You don't even think.",
             "who": "MAX", "pose": "point", "expr": "determined",
             "x": 0.5, "y": 0.92, "scale": 1.2, "facing": 1, "bg": "night"},
            {"id": "s003", "start": 8.0, "end": 12.0,
             "line": "You just catch it.",
             "who": "JAKE", "pose": "cheer", "expr": "happy",
             "x": 0.5, "y": 0.92, "scale": 1.1, "facing": -1, "bg": "dusk"},
            {"id": "s004", "start": 12.0, "end": 16.0,
             "line": "Your friend doesn't believe it.",
             "who": "MAX", "pose": "talk", "expr": "neutral",
             "who2": "JAKE", "pose2": "surprised", "expr2": "shocked",
             "x": 0.34, "x2": 0.68, "y": 0.92, "scale": 1.0, "bg": "dusk"},
        ],
    }
    path = os.path.join(out, "story.json")
    write(path, json.dumps(spec, indent=2))
    print("Wrote demo story ->", path)
    print("Now: python tools/director.py --story", path, "--out projects/director_demo")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--story")
    ap.add_argument("--out")
    ap.add_argument("--demo", action="store_true")
    args = ap.parse_args()
    if args.demo:
        return demo(args.out or "examples/director-demo")
    if not args.story or not args.out:
        sys.exit("ERROR: --story <json> and --out <projectdir> required (or --demo).")
    with open(args.story, encoding="utf-8") as f:
        spec = json.load(f)
    return build(spec, args.out)


if __name__ == "__main__":
    sys.exit(main())
