def _fig_scale(size, aspect):
    """Figure scale for a shot size — mirrors S_WIDE/S_MED in the emitted blocking.js."""
    vert = aspect == "9:16"
    return {"wide": 2.20 if vert else 1.45,
            "med": 2.70 if vert else 1.75,
            "close": 3.15 if vert else 2.60}.get(size, 2.20 if vert else 1.45)


def _walk_steps(w, aspect, size):
    """Footfalls in a walk — geometry, not a guess.

    walkAt() drives phase by distance: the planted foot travels 2*stride per PI of
    phase, so phase_total = PI * distLocal / (2*stride) and the number of plants is
    fixed. sound_design needs that count to land each footstep on a plant; a fixed
    0.30s grid only matches by luck and reads as skating.
    """
    import math
    ew = 1080 if aspect == "9:16" else 1920
    s = _fig_scale(size, aspect)
    dx = abs(float(w.get("to", .5)) - float(w.get("from", .5)))
    dist_local = dx * ew / max(.001, s)
    phase_total = math.pi * dist_local / (2 * float(w.get("stride", 26)))
    # walkPose puts the near foot on the ground from PI/2 to 3PI/2, so a plant
    # happens at PI/2 + n*PI — not on an even grid starting at zero.
    out, n = [], 0
    while math.pi / 2 + n * math.pi <= phase_total:
        out.append(round((math.pi / 2 + n * math.pi) / phase_total, 4))
        n += 1
    return out or [0.5]


